    private void tabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelMouseClicked
                                 
   int bar = tabel.getSelectedRow();

    String kode = tabel.getValueAt(bar, 0).toString(); // kode_pemeriksaan
    String regis = tabel.getValueAt(bar, 1).toString(); // no_registrasi
    String balita = tabel.getValueAt(bar, 2).toString(); // nama_balita
    String ortu = tabel.getValueAt(bar, 3).toString(); // orang_tua
    String status = tabel.getValueAt(bar, 4).toString(); // status_gizi

    kdpemeriksaan.setText(kode);
    gizi.setText(status);

    // set combobox no registrasi
    boolean found = false;
    for (int i = 0; i < noregis.getItemCount(); i++) {
        if (noregis.getItemAt(i).trim().equalsIgnoreCase(regis.trim())) {
            noregis.setSelectedIndex(i);
            found = true;
            break;
        }
    }

    if (!found) {
        JOptionPane.showMessageDialog(null,
            "No registrasi '" + regis + "' tidak ditemukan di ComboBox.\nCek data tb_balita.");
    }

    // OPTIONAL (aman meskipun sudah auto dari combobox)
    nmbalita.setText(balita);
    orangtua.setText(ortu);
    }//GEN-LAST:event_tabelMouseClicked

