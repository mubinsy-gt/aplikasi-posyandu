    private void noregisItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_noregisItemStateChanged
                                            
    if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {

        if (noregis.getSelectedIndex() == 0) {
            nmbalita.setText("");
            orangtua.setText("");
            return;
        }

        try {
            String sql = "SELECT nama_balita, orang_tua FROM tb_balita WHERE no_registrasi = ?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, noregis.getSelectedItem().toString());
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                nmbalita.setText(rs.getString("nama_balita"));
                orangtua.setText(rs.getString("orang_tua"));
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Gagal ambil data balita: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_noregisItemStateChanged

