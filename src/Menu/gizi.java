    public void tabel() {
    Object header[] = {
        "Kode Pemeriksaan",
        "No Registrasi",
        "Nama Balita",
        "Orang Tua",
        "Status Gizi"
    };

    DefaultTableModel data = new DefaultTableModel(null, header);
    tabel.setModel(data);

    try {
        String sql = "SELECT g.kode_pemeriksaan, g.no_registrasi, "
                   + "b.nama_balita, b.orang_tua, g.status_gizi "
                   + "FROM tb_gizi g "
                   + "JOIN tb_balita b ON g.no_registrasi = b.no_registrasi "
                   + "ORDER BY g.kode_pemeriksaan DESC";

        Statement stm = conn.createStatement();
        ResultSet rs = stm.executeQuery(sql);

        while (rs.next()) {
            Object[] row = {
                rs.getString("kode_pemeriksaan"),
                rs.getString("no_registrasi"),
                rs.getString("nama_balita"),
                rs.getString("orang_tua"),
                rs.getString("status_gizi")
            };
            data.addRow(row);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Data gagal dipanggil: " + e.getMessage());
    }
}

    
