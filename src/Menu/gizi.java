    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
                                     
    try {
        // VALIDASI WAJIB
        if (noregis.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(null, "Pilih No Registrasi terlebih dahulu");
            return;
        }

        if (nmbalita.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Nama balita belum terisi");
            return;
        }

        String sql = "INSERT INTO tb_gizi "
                   + "(kode_pemeriksaan, no_registrasi, nama_balita, orang_tua, status_gizi) "
                   + "VALUES (?,?,?,?,?)";

        PreparedStatement stat = conn.prepareStatement(sql);
        stat.setString(1, kdpemeriksaan.getText());
        stat.setString(2, noregis.getSelectedItem().toString());
        stat.setString(3, nmbalita.getText());   // 🔥 WAJIB
        stat.setString(4, orangtua.getText());
        stat.setString(5, gizi.getText());

        stat.executeUpdate();
        JOptionPane.showMessageDialog(null, "Data Gizi Berhasil Disimpan");

        tampilDataGizi();
        kosong();
        kdpemeriksaan.requestFocus();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Data gagal disimpan: " + e.getMessage());
    }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
  int ok = JOptionPane.showConfirmDialog(
        null,
        "Apakah yakin ingin mengubah data ini?",
        "Konfirmasi",
        JOptionPane.YES_NO_OPTION
    );

    if (ok == JOptionPane.YES_OPTION) {
        try {
            String sql = "UPDATE tb_gizi "
                       + "SET no_registrasi=?, status_gizi=? "
                       + "WHERE kode_pemeriksaan=?";

            PreparedStatement st = conn.prepareStatement(sql);
            st.setString(1, noregis.getSelectedItem().toString());
            st.setString(2, gizi.getText());
            st.setString(3, kdpemeriksaan.getText());

            int rows = st.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(null, "Update Data Berhasil");
                tampilDataGizi();
                kosong();
            } else {
                JOptionPane.showMessageDialog(null, "Data tidak ditemukan");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Update Data Gagal: " + e.getMessage());
        }
    }
 
    }//GEN-LAST:event_btnUbahActionPerformed

