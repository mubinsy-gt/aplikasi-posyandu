private void Selectbalita() {
    try {
        String sql = "SELECT no_registrasi FROM tb_balita ORDER BY no_registrasi ASC";
        Statement stm = conn.createStatement();
        ResultSet rs = stm.executeQuery(sql);

        noregis.removeAllItems();
        noregis.addItem("-- Pilih --");

        while (rs.next()) {
            noregis.addItem(rs.getString("no_registrasi").trim());
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
    }
}





