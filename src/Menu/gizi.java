public void tampilDataGizi() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("Kode Pemeriksaan");
    model.addColumn("No Registrasi");
    model.addColumn("Nama Balita");
    model.addColumn("Orang Tua");
    model.addColumn("Status Gizi");

    try {
        String sql = "SELECT g.kode_pemeriksaan, g.no_registrasi, "
                   + "b.nama_balita, b.orang_tua, g.status_gizi "
                   + "FROM tb_gizi g "
                   + "JOIN tb_balita b ON g.no_registrasi = b.no_registrasi "
                   + "ORDER BY g.kode_pemeriksaan ASC";

        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("kode_pemeriksaan"),
                rs.getString("no_registrasi"),
                rs.getString("nama_balita"),
                rs.getString("orang_tua"),
                rs.getString("status_gizi")
            });
        }

        tabel.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal menampilkan data: " + e.getMessage());
    }
}

    public void generateKodeGizi() {
        try {
        
            String sql = "SELECT * FROM tb_gizi ORDER by kode_pemeriksaan desc";
            java.sql.Statement stat = conn.createStatement();
            ResultSet r = stat.executeQuery(sql);

            if (r.next()) {
                String nofak = r.getString("kode_pemeriksaan").substring(1);
                String AN = "" + (Integer.parseInt(nofak) + 1);
                String Nol = "";

                if (AN.length() == 1) {
                    Nol = "000";
                } else if (AN.length() == 2) {
                    Nol = "00";
                } else if (AN.length() == 3) {
                    Nol = "0";
                } else if (AN.length() == 4) {
                    Nol = "";
                }

               kdpemeriksaan.setText("G" + Nol + AN);
            } else {
                kdpemeriksaan.setText("G0001");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }
    } 
    
