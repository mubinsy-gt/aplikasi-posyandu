    private void cariKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_cariKeyPressed
                             
        // Kolom tabel
    Object[] header = {"KODE IMUNISASI", "NAMA IMUNISASI", "USIA SASARAN", "JUMLAH DOSIS", "KETERANGAN", "STATUS"};
    DefaultTableModel data = new DefaultTableModel(null, header);
    tabel.setModel(data);

    try {
        String sql = "SELECT * FROM data_imunisasi WHERE "
                   + "nama_imunisasi LIKE '%" + cari.getText() + "%' "
                   + "OR usia_sasaran LIKE '%" + cari.getText() + "%' "
                   + "OR jumlah_dosis LIKE '%" + cari.getText() + "%' "
                   + "OR keterangan LIKE '%" + cari.getText() + "%' "
                   + "OR status_aktif LIKE '%" + cari.getText() + "%' "
                   + "ORDER BY kode_imunisasi ASC";

        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery(sql);

        while (rs.next()) {
            String[] row = {
                rs.getString("kode_imunisasi"),
                rs.getString("nama_imunisasi"),
                rs.getString("usia_sasaran"),
                rs.getString("jumlah_dosis"),
                rs.getString("keterangan"),
                rs.getString("status_aktif")
            };
            data.addRow(row);
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_cariKeyPressed

