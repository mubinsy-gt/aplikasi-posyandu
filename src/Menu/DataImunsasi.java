    private void tabelMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelMouseClicked
                                
    int bar = tabel.getSelectedRow();

    String a = tabel.getValueAt(bar, 0).toString(); // kode_imunisasi
    String b = tabel.getValueAt(bar, 1).toString(); // nama_imunisasi
    String c = tabel.getValueAt(bar, 2).toString(); // usia_sasaran
    String d = tabel.getValueAt(bar, 3).toString(); // jumlah_dosis
    String e = tabel.getValueAt(bar, 4).toString(); // keterangan
    String f = tabel.getValueAt(bar, 5).toString(); // status_aktif

    kdimun.setText(a);          // kode imunisasi
    nmimun.setText(b);          // nama imunisasi
    dosis.setText(d);           // jumlah dosis
    ket.setText(e);             // keterangan

    // set usia sesuai pilihan
    boolean found = false;
    for (int i = 0; i < usia.getItemCount(); i++) {
        if (usia.getItemAt(i).trim().equalsIgnoreCase(c.trim())) {
            usia.setSelectedIndex(i);
            found = true;
            break;
        }
    }
    if (!found) {
        usia.setSelectedIndex(0); // default kalau tidak cocok
    }

    // set radio button status
    if (f.equalsIgnoreCase("Aktif")) {
        rdaktif.setSelected(true);
    } else {
        rdtdkaktif.setSelected(true);
    }

    }//GEN-LAST:event_tabelMouseClicked

