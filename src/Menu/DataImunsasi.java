    private void cariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cariActionPerformed
    String key = cari.getText(); // ambil teks dari field cari
    String sql = "SELECT * FROM data_imunisasi "
               + "WHERE kode_imunisasi LIKE ? OR nama_imunisasi LIKE ?";

    try {
        PreparedStatement stat = conn.prepareStatement(sql);
        stat.setString(1, "%" + key + "%"); // cari berdasarkan kode
        stat.setString(2, "%" + key + "%"); // cari berdasarkan nama
        ResultSet rs = stat.executeQuery();

        // bikin model untuk tabel
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("Kode Imunisasi");
        model.addColumn("Nama Imunisasi");
        model.addColumn("Usia Sasaran");
        model.addColumn("Jumlah Dosis");
        model.addColumn("Keterangan");
        model.addColumn("Status");

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("kode_imunisasi"),
                rs.getString("nama_imunisasi"),
                rs.getString("usia_sasaran"),
                rs.getString("jumlah_dosis"),
                rs.getString("keterangan"),
                rs.getString("status_aktif")
            });
        }

        tabel.setModel(model); // tampilkan ke JTable

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Pencarian gagal: " + e.getMessage());
    }
    }//GEN-LAST:event_cariActionPerformed

