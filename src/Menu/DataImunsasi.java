   public void tabel() {
    Object header[] = {
        "KODE IMUNISASI", 
        "NAMA IMUNISASI", 
        "USIA SASARAN", 
        "JUMLAH DOSIS", 
        "KETERANGAN", 
        "STATUS"
    };
    DefaultTableModel data = new DefaultTableModel(null, header);
    tabel.setModel(data);

    setKoneksi(); // pastikan method ini bikin koneksi dan inisialisasi Statement (stm)

    String sql = "SELECT * FROM data_imunisasi ORDER BY kode_imunisasi ASC";
    try {
        ResultSet rs = stm.executeQuery(sql);
        while (rs.next()) {
            String kolom1 = rs.getString("kode_imunisasi");
            String kolom2 = rs.getString("nama_imunisasi");
            String kolom3 = rs.getString("usia_sasaran");
            String kolom4 = rs.getString("jumlah_dosis");
            String kolom5 = rs.getString("keterangan");
            String kolom6 = rs.getString("status_aktif");

            String kolom[] = {kolom1, kolom2, kolom3, kolom4, kolom5, kolom6};
            data.addRow(kolom);
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Data gagal dipanggil: " + e);
    }
}

    
