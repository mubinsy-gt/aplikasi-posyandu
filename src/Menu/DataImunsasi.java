public void tampilDataImunisasi() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("KODE IMUNISASI");   // 0
    model.addColumn("NAMA IMUNISASI");   // 1
    model.addColumn("USIA SASARAN");     // 2
    model.addColumn("JUMLAH DOSIS");     // 3
    model.addColumn("KETERANGAN");       // 4
    model.addColumn("STATUS");           // 5

    try {
        String sql = "SELECT * FROM data_imunisasi ORDER BY kode_imunisasi ASC";
        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery(sql);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("kode_imunisasi"),
                rs.getString("nama_imunisasi"),
                rs.getString("usia_sasaran"),
                rs.getInt("jumlah_dosis"),
                rs.getString("keterangan"),
                rs.getString("status_aktif")
            });
        }

        tabel.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal menampilkan data imunisasi: " + e.getMessage());
    }
}

    
 public void generateKodeImunisasi() {
    try {
        String sql = "SELECT kode_imunisasi FROM data_imunisasi "
                   + "WHERE kode_imunisasi IS NOT NULL AND kode_imunisasi <> '' "
                   + "ORDER BY CAST(SUBSTRING(kode_imunisasi, 2) AS UNSIGNED) DESC LIMIT 1";
        Statement stat = conn.createStatement();
        ResultSet r = stat.executeQuery(sql);

        if (r.next()) {
            String lastKode = r.getString("kode_imunisasi");
            
            // cek kalau string valid
            if (lastKode != null && lastKode.length() > 1) {
                int noUrut = Integer.parseInt(lastKode.substring(1)) + 1;
                kdimun.setText(String.format("K%03d", noUrut)); // K001, K002, K003
            } else {
                kdimun.setText("K001"); // fallback
            }
        } else {
            // Kalau tabel kosong → mulai dari K001
            kdimun.setText("K001");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal generate kode imunisasi: " + e.getMessage());
    }
}





    
